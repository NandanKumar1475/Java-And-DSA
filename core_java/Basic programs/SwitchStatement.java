class SwitchStatement{
	public static void main(String[] args){
		int choice = 2 ;
		switch(choice){
			case 1 :
			System.out.println("upi");
			break;
			
			case 2 :
			System.out.println("cod");
			break;
			
			case 3:
			System.out.println("card");
			break;
			
			case 4:
			System.out.println("net banking");
			break;
			
			default: 
			System.out.println("invalid choice");
			
			
		}
	}
}