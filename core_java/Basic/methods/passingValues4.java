class passingValues4{
	static char run(){
		return 'j';
	}
	
	// returning double value 
	static boolean disp(){
		return true;
	}
	
	public static void main(String[] args){
		System.out.println("returning char values= " + run());
		boolean b = disp();
		
		System.out.println("returning boolean values = " + b);
		
		
	}
}