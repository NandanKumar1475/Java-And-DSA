class switchwithchar{
	public static void main(String[] args){
		char ch= 'a' ;
		switch(ch){
			
			case 'a':
			System.out.println("Apple");
			break;
			case 'b' :
			System.out.println("ball");
			break;
			case 'c' : 
			System.out.println("cat");
			break ;
			case 'd' : 
			System.out.println("dog");
			break ;
			
			default :
			System.out.println("under development");
		}
			
	}
}